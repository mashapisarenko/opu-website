    if n: return n
    t = p["title"]
    b = brand_of(p)
    if b: t = re.sub(r"^" + re.escape(b) + r"\s+", "", t, flags=re.I)
    t = re.split(r",| - | – |: | with | for | \(", t)[0].strip()
    if len(t) > 55: t = t[:55].rsplit(" ", 1)[0]
    return t

