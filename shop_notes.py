def _clean_reason(r):
    parts = [x.strip() for x in re.split(r";|,\s+", r) if x.strip()]
    # re-join clauses that were split only by a comma inside a list (keep order)
    keep = [x for x in parts if not BAD.search(x)]
    s = ", ".join(keep).strip(" ,;")
    s = re.sub(r"\s*\(per [a-z]+\)", "", s)
    return s

